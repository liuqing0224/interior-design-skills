// Kept for reference; export_budget.py writes the same workbook, evidence and
// previews with openpyxl and no external service.
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import path from 'node:path';
import crypto from 'node:crypto';
import { Workbook, SpreadsheetFile } from '@oai/artifact-tool';

if(!process.argv[2]) throw new Error('Pass the project directory');
const project=path.resolve(process.argv[2]);
const model=JSON.parse(await fs.readFile(`${project}/model/project.json`,'utf8'));
const expected=JSON.parse(await fs.readFile(`${project}/schedules/budget-summary.json`,'utf8'));
const budgetInputs=JSON.parse(await fs.readFile(`${project}/schedules/budget-inputs.json`,'utf8'));
const book=Workbook.create();
const summary=book.worksheets.add('预算总览');
const detail=book.worksheets.add('工程量计价');
for (const sheet of [summary,detail]) sheet.showGridLines=false;
summary.tabColor='#435D4E';detail.tabColor='#AE9472';
summary.getRange('B2').values=[[`${model.title} 室内设计预算`]];
summary.getRange('B3').values=[[`${model.project_id} / ${model.revision} / CNY`]];
summary.getRange('B5:C6').values=[['目标总预算',model.budget_cny],['预备费率',model.reserve_rate]];
summary.getRange('E5').values=[['蓝色数字为可调整输入']];
summary.getRange('B9:C9').values=[['费用类别','金额（元）']];
const categories=[...new Set(model.budget.map(x=>x.category))];
const first=5,last=first+model.budget.length-1;
const baseRow=Math.max(19,11+categories.length),reserveRow=baseRow+1,totalRow=baseRow+2,remainingRow=baseRow+3;
if(!model.budget.length) throw new Error('Budget must contain at least one line');
detail.getRange('A2').values=[['工程量、损耗与单价']];
detail.getRange('A3').values=[['单价为本项目估算输入；净量由当前模型导出，来源和计量口径见J列。']];
detail.getRange('A4:J4').values=[['编号','类别','工作内容','净量','单位','损耗率','计价量','单价（元）','金额（元）','计量依据']];
const values=budgetInputs.map(x=>[x.id,x.category,x.name,x.quantity,x.unit,x.waste,null,x.rate,null,x.basis]);
detail.getRange(`A${first}:J${last}`).values=values;
detail.getRange(`G${first}`).formulas=[[`=IF(COUNT(D${first},F${first})=2,ROUND(D${first}*(1+F${first}),4),"缺少输入")`]];
detail.getRange(`G${first}:G${last}`).fillDown();
detail.getRange(`I${first}`).formulas=[[`=IF(COUNT(G${first},H${first})=2,ROUND(G${first}*H${first},2),"缺少输入")`]];
detail.getRange(`I${first}:I${last}`).fillDown();
categories.forEach((c,i)=>{
 const r=10+i;summary.getRange(`B${r}`).values=[[c]];
 summary.getRange(`C${r}`).formulas=[[`=IF(COUNT('工程量计价'!I${first}:I${last})=${model.budget.length},SUMIFS('工程量计价'!$I$${first}:$I$${last},'工程量计价'!$B$${first}:$B$${last},B${r}),"缺少计价输入")`]];
});
summary.getRange(`B${baseRow}:B${remainingRow}`).values=[['基础费用合计'],['预备费'],['含预备费总额'],['预算余量']];
summary.getRange(`C${baseRow}`).formulas=[[`=IF(COUNT('工程量计价'!I${first}:I${last})=COUNTA('工程量计价'!A${first}:A${last}),SUM('工程量计价'!I${first}:I${last}),"缺少计价输入")`]];
summary.getRange(`C${reserveRow}`).formulas=[[`=IF(AND(ISNUMBER(C${baseRow}),ISNUMBER(C6)),ROUND(C${baseRow}*C6,2),"缺少计价输入")`]];
summary.getRange(`C${totalRow}`).formulas=[[`=IF(COUNT(C${baseRow}:C${reserveRow})=2,SUM(C${baseRow}:C${reserveRow}),"缺少计价输入")`]];
summary.getRange(`C${remainingRow}`).formulas=[[`=IF(AND(ISNUMBER(C5),ISNUMBER(C${totalRow})),ROUND(C5-C${totalRow},2),"缺少计价输入")`]];
summary.getRange(`E${baseRow}`).values=[[`${budgetInputs.filter(x=>x.quantity_rule).length}/${budgetInputs.length}行工程量由模型规则计量；其余为明确输入。`]];
summary.getRange(`E${totalRow}`).values=[['费用范围以本项目明细为准。']];

summary.getRange(`B2:F${remainingRow+1}`).format.font={name:'Arial',size:11,color:'#263A30'};
summary.getRange('B2').format.font={name:'Arial',size:16,color:'#263A30'};
summary.getRange('B3:F3').format.font={name:'Arial',size:10,color:'#7D8178'};
summary.getRange('B:B').format.columnWidth=26;
summary.getRange('C:C').format.columnWidth=20;
summary.getRange('D:D').format.columnWidth=4;
summary.getRange('E:E').format.columnWidth=64;
summary.getRange('B5:C6').format.rowHeight=26;
summary.getRange(`B9:C${remainingRow}`).format.rowHeight=27;
summary.getRange('B9:C9').format={fill:'#435D4E',font:{name:'Arial',size:11,color:'#FFFFFF',bold:true},rowHeight:29};
summary.getRange('C5:C6').format.font.color='#1D5CBD';
summary.getRange('C5').format.numberFormat='#,##0.00';summary.getRange('C6').format.numberFormat='0.0%';
summary.getRange(`C10:C${remainingRow}`).format.numberFormat='#,##0.00';
summary.getRange(`B${baseRow}:C${baseRow}`).format.borders={top:{style:'thin',color:'#AE9472'}};
summary.getRange(`B${totalRow}:C${totalRow}`).format={fill:'#E7EBDD',font:{name:'Arial',size:12,bold:true,color:'#263A30'}};
summary.getRange(`E5:E${remainingRow}`).format.font={name:'Arial',size:10,color:'#777B70'};
summary.getRange(`C${remainingRow}`).conditionalFormats.add('cellIs',{operator:'lessThan',formula:0,format:{fill:'#F7D8D3',font:{color:'#AE3425',bold:true}}});
detail.getRange(`A2:J${last}`).format.font={name:'Arial',size:10,color:'#24382E'};
detail.getRange('A2').format.font={name:'Arial',size:15,color:'#263A30'};
detail.getRange('A3').format.font={name:'Arial',size:10,color:'#777B70'};
detail.getRange('A4:J4').format={fill:'#435D4E',font:{name:'Arial',size:10,color:'#FFFFFF',bold:true},rowHeight:30};
const widths={A:11,B:11,C:31,D:12,E:9,F:10,G:13,H:15,I:17,J:58};
for(const [col,width] of Object.entries(widths)) detail.getRange(`${col}:${col}`).format.columnWidth=width;
detail.getRange(`A${first}:J${last}`).format.rowHeight=32;
detail.getRange(`J${first}:J${last}`).format.wrapText=true;
detail.getRange(`D${first}:D${last}`).format.numberFormat='0.0000';
detail.getRange(`G${first}:G${last}`).format.numberFormat='0.0000';
detail.getRange(`F${first}:F${last}`).format.numberFormat='0.0%';
detail.getRange(`H${first}:I${last}`).format.numberFormat='#,##0.00';
for(const col of ['D','F','H']) detail.getRange(`${col}${first}:${col}${last}`).format.font.color='#1D5CBD';
detail.freezePanes.freezeRows(4);detail.freezePanes.freezeColumns(3);
book.recalculate();
const num=(cell)=>summary.getRange(cell).values[0][0];
assert.equal(Math.round(num(`C${totalRow}`)*100),Math.round(expected.total*100));
assert.ok(Math.abs(num(`C${remainingRow}`)-expected.remaining)<.01);
const original=model.budget[0].rate;
detail.getRange('H5').values=[[original+10]];book.recalculate();
const changed=num(`C${totalRow}`);assert.ok(changed>expected.total);
detail.getRange('H5').values=[[null]];book.recalculate();assert.equal(num(`C${totalRow}`),'缺少计价输入');assert.equal(num('C10'),'缺少计价输入');
detail.getRange('H5').values=[[0]];book.recalculate();assert.ok(typeof num(`C${totalRow}`)==='number'&&num(`C${totalRow}`)<expected.total);
detail.getRange('H5').values=[[original]];book.recalculate();assert.ok(Math.abs(num(`C${totalRow}`)-expected.total)<.01);
const errors=await book.inspect({kind:'match',searchTerm:'#REF!|#DIV/0!|#VALUE!|#NAME\\?|#N/A|#NUM!|#NULL!',options:{useRegex:true,maxResults:20},maxChars:1000});
await fs.writeFile(`${project}/state/workbook-error-scan.txt`,errors.ndjson);
await fs.writeFile(`${project}/state/workbook-check.json`,JSON.stringify({revision:model.revision,total:num(`C${totalRow}`),remaining:num(`C${remainingRow}`),independentTotal:expected.total,input_change_recalculated:changed,missing_input_exposed:true,zero_preserved:true,restored:true,engine:'artifact-tool',cells:{base:`C${baseRow}`,reserve:`C${reserveRow}`,total:`C${totalRow}`,remaining:`C${remainingRow}`}},null,2));
const sample=await book.inspect({kind:'table',range:`工程量计价!A5:J${Math.min(last,8)}`,include:'values,formulas',tableMaxRows:4,tableMaxCols:10,maxChars:1800});
await fs.writeFile(`${project}/state/workbook-key-ranges.txt`,sample.ndjson);
for(const [sheetName,range,file] of [['预算总览',`B2:E${remainingRow+1}`,'budget-summary-preview.png'],['工程量计价','A2:J16','budget-detail-preview.png']]){
 const preview=await book.render({sheetName,range,scale:1.4,format:'png'});await fs.writeFile(`${project}/state/${file}`,new Uint8Array(await preview.arrayBuffer()));
}
const exported=await SpreadsheetFile.exportXlsx(book);await exported.save(`${project}/schedules/${model.title}_预算.xlsx`);
const sha=value=>crypto.createHash('sha256').update(value).digest('hex');
const evidence=JSON.parse(await fs.readFile(`${project}/state/workbook-check.json`,'utf8'));
evidence.model_sha256=sha(await fs.readFile(`${project}/model/project.json`));
evidence.xlsx_sha256=sha(await fs.readFile(`${project}/schedules/${model.title}_预算.xlsx`));
await fs.writeFile(`${project}/state/workbook-check.json`,JSON.stringify(evidence,null,2));
console.log(JSON.stringify({total:num(`C${totalRow}`),remaining:num(`C${remainingRow}`),rows:model.budget.length,exported:true}));
